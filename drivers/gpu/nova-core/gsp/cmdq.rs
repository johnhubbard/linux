/// Marker type representing the absence of a reply for a command. Commands using this as their
/// reply type are sent using [`Cmdq::send_command_no_wait`].
pub(crate) struct NoReply;

/// Trait implemented by types representing a command to send to the GSP.
///
/// The main purpose of this trait is to provide [`Cmdq`] with the information it needs to send
/// a given command.
///
/// [`CommandToGsp::init`] in particular is responsible for initializing the command directly
/// into the space reserved for it in the command queue buffer.
///
/// Some commands may be followed by a variable-length payload. For these, the
/// [`CommandToGsp::variable_payload_len`] and [`CommandToGsp::init_variable_payload`] need to be
/// defined as well.
pub(crate) trait CommandToGsp {
    /// Function identifying this command to the GSP.
    const FUNCTION: MsgFunction;

    /// Type generated by [`CommandToGsp::init`], to be written into the command queue buffer.
    type Command: FromBytes + AsBytes;

    /// Type of the reply expected from the GSP, or [`NoReply`] for commands that don't
    /// have a reply.
    type Reply;

    /// Error type returned by [`CommandToGsp::init`].
    type InitError;

    /// In-place command initializer responsible for filling the command in the command queue
    /// buffer.
    fn init(&self) -> impl Init<Self::Command, Self::InitError>;

    /// Size of the variable-length payload following the command structure generated by
    /// [`CommandToGsp::init`].
    ///
    /// Most commands don't have a variable-length payload, so this is zero by default.
    fn variable_payload_len(&self) -> usize {
        0
    }

    /// Method initializing the variable-length payload.
    ///
    /// The command buffer is circular, which means that we may need to jump back to its beginning
    /// while in the middle of a command. For this reason, the variable-length payload is
    /// initialized using a [`SBufferIter`].
    ///
    /// This method will receive a buffer of the length returned by
    /// [`CommandToGsp::variable_payload_len`], and must write every single byte of it. Leaving
    /// unwritten space will lead to an error.
    ///
    /// Most commands don't have a variable-length payload, so this does nothing by default.
    fn init_variable_payload(
        &self,
        _dst: &mut SBufferIter<core::array::IntoIter<&mut [u8], 2>>,
    ) -> Result {
        Ok(())
    }

    /// Total size of the command (including its variable-length payload) without the
    /// [`GspMsgElement`] header.
    fn size(&self) -> usize {
        size_of::<Self::Command>() + self.variable_payload_len()
    }
}

/// Trait representing messages received from the GSP.
///
/// A reply that [`Cmdq::send_command`] waits for, or an event that [`Cmdq::await_msg`] waits for.
/// The receiver matches a message's function code against [`Self::FUNCTION`] and decodes the
/// message with [`Self::read`].
pub(crate) trait MessageFromGsp: Sized {
    /// Function identifying this message from the GSP.
    const FUNCTION: MsgFunction;

    /// Error type returned by [`MessageFromGsp::read`].
    type InitError;

    /// Type containing the raw message to be read from the message queue.
    type Message: FromBytes;

    /// Method reading the message from the message queue and returning it.
    ///
    /// From a `Self::Message` and a [`SBufferIter`], constructs an instance of `Self` and returns
    /// it.
    fn read(
        msg: &Self::Message,
        sbuffer: &mut SBufferIter<core::array::IntoIter<&[u8], 2>>,
    ) -> Result<Self, Self::InitError>;
}

/// Number of GSP pages making the [`Msgq`].
pub(crate) const MSGQ_NUM_PAGES: u32 = 0x3f;

/// Circular buffer of a [`Msgq`].
///
/// This area of memory is to be shared between the driver and the GSP to exchange commands or
/// messages.
#[repr(C, align(0x1000))]
#[derive(Debug)]
struct MsgqData {
    data: [[u8; GSP_PAGE_SIZE]; num::u32_as_usize(MSGQ_NUM_PAGES)],
}

// Annoyingly we are forced to use a literal to specify the alignment of
// `MsgqData`, so check that it corresponds to the actual GSP page size here.
static_assert!(align_of::<MsgqData>() == GSP_PAGE_SIZE);

/// Unidirectional message queue.
///
/// Contains the data for a message queue, that either the driver or GSP writes to.
///
/// The queue pointers are in BAR0 registers, so `tx` carries the queue's geometry alone. `msgq`
/// is aligned to [`GSP_PAGE_SIZE`], and the bytes between the two are zero padding.
#[repr(C)]
// The firmware headers declare no struct for this layout.
struct Msgq {
    /// Header describing the queue.
    tx: MsgqTxHeader,
    /// The message queue proper.
    msgq: MsgqData,
}

/// Structure shared between the driver and the GSP and containing the command and message queues.
#[repr(C)]
struct GspMem {
    /// Self-mapping page table entries.
    ptes: PteArray<{ Self::PTE_ARRAY_SIZE }>,
    /// CPU queue: the driver writes commands here, and the GSP reads them.
    ///
    /// This member is read-only for the GSP.
    cpuq: Msgq,
    /// GSP queue: the GSP writes messages here, and the driver reads them.
    ///
    /// This member is read-only for the driver.
    gspq: Msgq,
}

impl GspMem {
    const PTE_ARRAY_SIZE: usize = GSP_PAGE_SIZE / size_of::<u64>();
}

// SAFETY: These structs don't meet the no-padding requirements of AsBytes but
// that is not a problem because they are not used outside the kernel.
unsafe impl AsBytes for GspMem {}

// SAFETY: These structs don't meet the no-padding requirements of FromBytes but
// that is not a problem because they are not used outside the kernel.
unsafe impl FromBytes for GspMem {}

/// Wrapper around [`GspMem`] to share it with the GPU using a [`Coherent`].
///
/// This provides the low-level functionality to communicate with the GSP, including allocation of
/// queue space to write messages to and management of read/write pointers.
///
/// This is shared with the GSP, with clear ownership rules regarding the command queues:
///
/// * The driver owns (i.e. can write to) the part of the CPU message queue between the CPU write
///   pointer and the GSP read pointer. This region is returned by [`Self::driver_write_area`].
/// * The driver owns (i.e. can read from) the part of the GSP message queue between the CPU read
///   pointer and the GSP write pointer. This region is returned by [`Self::driver_read_area`].
///
/// Each pointer counts elements without wrapping at the ring size: a ring is empty when its two
/// pointers are equal and full when they differ by the ring size. A GSP reset zeroes all four
/// pointer registers, so the driver keeps its own two pointers here and writes them out, and it
/// keeps the last value it read of the GSP's two, which stands in while a register reads as zero.
struct DmaGspMem<'a> {
    /// The queues, mapped for the GSP.
    mem: Coherent<'a, GspMem>,
    /// MMIO mapping of PCI BAR 0, for the queue pointer registers.
    bar: Bar0<'a>,
    /// Number of elements the driver has written to the command queue, published to the GSP
    /// through `NV_PGSP_QUEUE_HEAD`.
    cpu_write_ptr: u32,
    /// Number of elements the driver has consumed from the message queue, published to the GSP
    /// through `NV_PGSP_MSGQ_TAIL`.
    cpu_read_ptr: u32,
    /// The GSP's count of consumed commands, as last read from `NV_PGSP_QUEUE_TAIL`.
    last_gsp_read_ptr: Cell<u32>,
    /// The GSP's count of posted messages, as last read from `NV_PGSP_MSGQ_HEAD`.
    last_gsp_write_ptr: Cell<u32>,
}

impl<'a> DmaGspMem<'a> {
    /// Allocate a new instance and map it for `dev`.
    fn new(dev: &'a device::Device<device::Bound>, bar: Bar0<'a>) -> Result<Self> {
        const MSGQ_SIZE: u32 = num::usize_into_u32::<{ size_of::<Msgq>() }>();
        const MSG_SIZE: u32 = num::usize_into_u32::<GSP_PAGE_SIZE>();
        const ENTRY_OFF: u32 = num::usize_into_u32::<{ mem::offset_of!(Msgq, msgq) }>();

        let mut gsp_mem = CoherentBox::<'_, GspMem>::zeroed(dev, GFP_KERNEL)?;
        gsp_mem.cpuq.tx = MsgqTxHeader::new(MSGQ_SIZE, MSG_SIZE, MSGQ_NUM_PAGES, ENTRY_OFF);

        let gsp_mem: Coherent<'_, _> = gsp_mem.into();
        PteArray::init(io_project!(gsp_mem, .ptes), gsp_mem.dma_address())?;

        Ok(Self {
            mem: gsp_mem,
            bar,
            cpu_write_ptr: 0,
            cpu_read_ptr: 0,
            last_gsp_read_ptr: Cell::new(0),
            last_gsp_write_ptr: Cell::new(0),
        })
    }

    /// Returns the region of the CPU message queue that the driver may write to. The ring wraps,
    /// so the region comes as two slices, and the second is empty unless the region crosses the
    /// end of the ring.
    fn driver_write_area(&mut self) -> (&mut [[u8; GSP_PAGE_SIZE]], &mut [[u8; GSP_PAGE_SIZE]]) {
        let used = self.cpu_write_ptr.wrapping_sub(self.gsp_read_ptr());
        let avail = num::u32_as_usize(MSGQ_NUM_PAGES.saturating_sub(used));
        let w_slot = num::u32_as_usize(self.cpu_write_ptr % MSGQ_NUM_PAGES);

        // Pointer to the first entry of the CPU message queue.
        let data = ptr::project!(mut self.mem.as_mut_ptr(), .cpuq.msgq.data[build: 0]);

        // SAFETY:
        // - `data` points to the `MSGQ_NUM_PAGES` initialized entries of the CPU message queue.
        // - The returned slices cover the `avail` free slots from the write pointer on, which the
        //   GSP does not read until `advance_cpu_write_ptr` publishes them.
        // - `split_at_mut` gives two non-overlapping halves, and the `&mut self` borrow lasts as
        //   long as the returned slices, so nothing else hands out the same region.
        let data =
            unsafe { core::slice::from_raw_parts_mut(data, num::u32_as_usize(MSGQ_NUM_PAGES)) };
        let (before_w, after_w) = data.split_at_mut(w_slot);

        let in_after = avail.min(after_w.len());
        let in_before = avail - in_after;
        (&mut after_w[..in_after], &mut before_w[..in_before])
    }

    /// Returns the number of bytes the driver can still write to the command queue: the slots
    /// between the driver's write pointer and the GSP's read pointer, times the slot size.
    fn driver_write_area_size(&self) -> usize {
        let used = self.cpu_write_ptr.wrapping_sub(self.gsp_read_ptr());
        let slots = MSGQ_NUM_PAGES.saturating_sub(used);
        num::u32_as_usize(slots) * GSP_PAGE_SIZE
    }

    /// Returns the region of the GSP message queue that the driver may read, as two slices
    /// because the ring wraps.
    fn driver_read_area(&self) -> (&[[u8; GSP_PAGE_SIZE]], &[[u8; GSP_PAGE_SIZE]]) {
        let avail = num::u32_as_usize(self.gsp_write_ptr().wrapping_sub(self.cpu_read_ptr));
        let r_slot = num::u32_as_usize(self.cpu_read_ptr % MSGQ_NUM_PAGES);

        // Pointer to the first entry of the GSP message queue.
        let data = ptr::project!(self.mem.as_ptr(), .gspq.msgq.data[build: 0]);

        // SAFETY:
        // - `data` points to the `MSGQ_NUM_PAGES` initialized entries of the GSP message queue.
        // - The returned slices cover the `avail` slots the GSP has already written and does not
        //   write again until `advance_cpu_read_ptr` releases them.
        let data = unsafe { core::slice::from_raw_parts(data, num::u32_as_usize(MSGQ_NUM_PAGES)) };
        let (before_r, after_r) = data.split_at(r_slot);

        let in_after = avail.min(after_r.len());
        let in_before = avail - in_after;
        (&after_r[..in_after], &before_r[..in_before])
    }

    /// Allocates a region on the command queue that is large enough to send a command of `size`
    /// bytes, waiting for space to become available based on the provided timeout.
    ///
    /// This returns a [`GspCommand`] ready to be written to by the caller.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command is larger than [`GSP_MSG_QUEUE_ELEMENT_SIZE_MAX`].
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the command header is not properly aligned.
    fn allocate_command<H: FromBytes + AsBytes>(
        &mut self,
        size: usize,
        timeout: Delta,
    ) -> Result<GspCommand<'_, H>> {
        if size_of::<H>() + size > GSP_MSG_QUEUE_ELEMENT_SIZE_MAX {
            return Err(EMSGSIZE);
        }
        read_poll_timeout(
            || Ok(self.driver_write_area_size()),
            |available_bytes| *available_bytes >= size_of::<H>() + size,
            Delta::from_micros(1),
            timeout,
        )?;

        // Get the current writable area as an array of bytes.
        let (slice_1, slice_2) = {
            let (slice_1, slice_2) = self.driver_write_area();

            (slice_1.as_flattened_mut(), slice_2.as_flattened_mut())
        };

        let (header, slice_1) = H::from_bytes_mut_prefix(slice_1).ok_or(EIO)?;

        // Create the contents area.
        let (slice_1, slice_2) = if slice_1.len() > size {
            // Contents fits entirely in `slice_1`.
            (&mut slice_1[..size], &mut slice_2[0..0])
        } else {
            // Need all of `slice_1` and some of `slice_2`.
            let slice_2_len = size - slice_1.len();
            (slice_1, &mut slice_2[..slice_2_len])
        };

        Ok(GspCommand {
            header,
            contents: (slice_1, slice_2),
        })
    }

    /// Returns the GSP's count of posted messages.
    fn gsp_write_ptr(&self) -> u32 {
        // ORDERING: `readl` ends in a read barrier, which orders this read before the data reads
        // that follow it.
        let ptr = *self.bar.read(regs::NV_PGSP_MSGQ_HEAD).address();

        // A zeroed register is a GSP reset, not a count. Nothing new is readable until GSP-RM posts
        // a message and writes the register back.
        if ptr.wrapping_sub(self.cpu_read_ptr) > MSGQ_NUM_PAGES {
            return self.last_gsp_write_ptr.get();
        }
        self.last_gsp_write_ptr.set(ptr);

        ptr
    }

    /// Returns the GSP's count of consumed commands.
    fn gsp_read_ptr(&self) -> u32 {
        let ptr = *self.bar.read(regs::NV_PGSP_QUEUE_TAIL).address();

        // ORDERING: the data writes that follow must not pass this read. `readl` orders only the
        // reads that follow it, so the writes need a full barrier.
        dma_mb(Full);

        // A zeroed register is a GSP reset, not a count. The last count read stands in until GSP-RM
        // consumes a command and writes the register back, and undercounts the free space at worst.
        if self.cpu_write_ptr.wrapping_sub(ptr) > MSGQ_NUM_PAGES {
            return self.last_gsp_read_ptr.get();
        }
        self.last_gsp_read_ptr.set(ptr);

        ptr
    }

    /// Releases `elem_count` more elements of the message queue to the GSP.
    fn advance_cpu_read_ptr(&mut self, elem_count: u32) {
        self.cpu_read_ptr = self.cpu_read_ptr.wrapping_add(elem_count);

        // ORDERING: the data reads must complete before this write releases the slots to the GSP.
        // `writel` orders only the writes before it, so the reads need a full barrier.
        dma_mb(Full);

        self.bar
            .write_reg(regs::NV_PGSP_MSGQ_TAIL::zeroed().with_address(self.cpu_read_ptr));
    }

    /// Publishes `elem_count` more elements of the command queue to the GSP, which the write to
    /// `NV_PGSP_QUEUE_HEAD` also interrupts.
    fn advance_cpu_write_ptr(&mut self, elem_count: u32) {
        self.cpu_write_ptr = self.cpu_write_ptr.wrapping_add(elem_count);

        // ORDERING: `writel` begins with a write barrier, which orders the data writes before this
        // register write.
        self.bar
            .write_reg(regs::NV_PGSP_QUEUE_HEAD::zeroed().with_address(self.cpu_write_ptr));
    }
}

/// A command ready to be sent on the command queue.
///
/// `H` is the element header this command carries, such as [`GspMsgElement`] for an RM RPC.
///
/// This is the type returned by [`DmaGspMem::allocate_command`].
struct GspCommand<'a, H> {
    // Writable reference to the header of the command.
    header: &'a mut H,
    // Writable slices to the contents of the command. The second slice is zero unless the command
    // loops over the command queue.
    contents: (&'a mut [u8], &'a mut [u8]),
}

/// An RPC message ready to be processed from the message queue.
///
/// This is the [`QueueElement::Rpc`] payload.
struct GspMessage<'a> {
    // Reference to the header of the message.
    header: &'a GspMsgElement,
    // Slices to the contents of the message. The second slice is zero unless the message loops
    // over the message queue.
    contents: (&'a [u8], &'a [u8]),
}

/// A GMC message ready to be processed from the message queue.
///
/// This is the [`QueueElement::Gmc`] payload.
struct GmcMessage<'a> {
    // Reference to the headers of the message.
    header: &'a GspGmcMsgElement,
    // Slices to the payload that follows the GMC header. The second slice is empty unless the
    // payload wraps around the end of the message queue.
    contents: (&'a [u8], &'a [u8]),
}

/// A queue element with valid transport framing, decoded as the kind of message its NVDM type
/// names.
///
/// This is the type returned by [`CmdqInner::wait_for_element`].
enum QueueElement<'a> {
    /// An RM RPC message.
    Rpc(GspMessage<'a>),
    /// A GMC API message.
    Gmc(GmcMessage<'a>),
}

impl QueueElement<'_> {
    /// Returns the number of queue slots the element occupies.
    fn element_count(&self) -> u32 {
        match self {
            Self::Rpc(message) => message.header.element_count(),
            Self::Gmc(message) => message.header.element_count(),
        }
    }
}

/// GSP command queue.
///
/// Provides the ability to send commands and receive messages from the GSP using a shared memory
/// area.
#[pin_data]
pub(crate) struct Cmdq<'cmdq> {
    /// Inner mutex-protected state.
    #[pin]
    inner: Mutex<CmdqInner<'cmdq>>,
    /// DMA address of the command queue's shared memory region.
    pub(super) dma_addr: DmaAddress,
}

impl<'cmdq> Cmdq<'cmdq> {
    /// Offset of the data after the PTEs.
    const POST_PTE_OFFSET: usize = core::mem::offset_of!(GspMem, cpuq);

    /// Offset of command queue ring buffer.
    pub(crate) const CMDQ_OFFSET: usize = core::mem::offset_of!(GspMem, cpuq)
        + core::mem::offset_of!(Msgq, msgq)
        - Self::POST_PTE_OFFSET;

    /// Offset of message queue ring buffer.
    pub(crate) const STATQ_OFFSET: usize = core::mem::offset_of!(GspMem, gspq)
        + core::mem::offset_of!(Msgq, msgq)
        - Self::POST_PTE_OFFSET;

    /// Number of page table entries for the GSP shared region.
    pub(crate) const NUM_PTES: usize = size_of::<GspMem>() >> GSP_PAGE_SHIFT;

    /// Default timeout for receiving a message from the GSP.
    pub(super) const RECEIVE_TIMEOUT: Delta = Delta::from_secs(5);

    /// Creates a new command queue for `dev`.
    pub(crate) fn new(
        dev: &'cmdq device::Device<device::Bound>,
        bar: Bar0<'cmdq>,
    ) -> impl PinInit<Self, Error> + 'cmdq {
        pin_init_scope(move || {
            let gsp_mem = DmaGspMem::new(dev, bar)?;

            Ok(try_pin_init!(Self {
                dma_addr: gsp_mem.mem.dma_address(),
                inner <- new_mutex!(CmdqInner {
                    dev,
                    gsp_mem,
                    rpc_seq: 0,
                    poisoned: Cell::new(false),
                }),
            }))
        })
    }

    /// Sends `command` to the GSP and waits for the reply.
    ///
    /// Events that arrive before the reply are logged and consumed.
    ///
    /// The queue is locked for the entire send+receive cycle to ensure that no other command can
    /// be interleaved.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if space does not become available to send the command, or if the reply does
    ///   not arrive within [`Self::RECEIVE_TIMEOUT`] of the send, however many events arrive
    ///   while waiting.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command and reply initializers are propagated as-is.
    #[expect(dead_code)]
    pub(crate) fn send_command<M>(&self, command: M) -> Result<M::Reply>
    where
        M: CommandToGsp,
        M::Reply: MessageFromGsp,
        Error: From<M::InitError>,
        Error: From<<M::Reply as MessageFromGsp>::InitError>,
    {
        let mut inner = self.inner.lock();
        let expected_seq = inner.send_command(command)?;

        inner.await_msg(Some(expected_seq))
    }

    /// Sends `command` to the GSP without waiting for a reply.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializers are propagated as-is.
    #[expect(dead_code)]
    pub(crate) fn send_command_no_wait<M>(&self, command: M) -> Result
    where
        M: CommandToGsp<Reply = NoReply>,
        Error: From<M::InitError>,
    {
        self.inner.lock().send_command(command).map(|_| ())
    }

    /// Receives one queue element. A GMC element goes to `handler` with its GMC header fields and
    /// its payload slices. An RPC element is logged as an event.
    ///
    /// This method may sleep while waiting. The queue mutex stays locked across the wait and the
    /// `handler` call, so `handler` must not call back into this [`Cmdq`].
    ///
    /// See [`CmdqInner::receive_gmc_and_dispatch`] for the return value and the errors.
    pub(crate) fn receive_gmc_and_dispatch<R>(
        &self,
        timeout: Delta,
        handler: impl FnOnce(u32, u32, &[u8], &[u8]) -> Option<R>,
    ) -> Result<Option<R>> {
        self.inner.lock().receive_gmc_and_dispatch(timeout, handler)
    }

    /// Sends a GMC API request to the GSP without waiting for the response.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the request exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if queue space does not become available within the timeout.
    /// - `EIO` if the element header is not properly aligned.
    pub(crate) fn send_gmc_no_wait(
        &self,
        command_id: u32,
        payload: &[u8],
        max_response_size: u32,
    ) -> Result {
        self.inner
            .lock()
            .send_gmc(command_id, payload, max_response_size)
    }

    /// Waits for an unsolicited GSP event of type `M`. Events that arrive before it are logged and
    /// consumed.
    ///
    /// The event answers no command, so it is matched on its function code alone.
    ///
    /// The queue mutex is held for the whole wait, up to [`Self::RECEIVE_TIMEOUT`], so no other
    /// caller can send a command or consume an event meanwhile.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if the event does not arrive within [`Self::RECEIVE_TIMEOUT`] of the call,
    ///   however many other events arrive while waiting.
    /// - `EIO` if the queue is poisoned, or if a message fails framing validation.
    ///
    /// Error codes returned by [`MessageFromGsp::read`] are propagated as-is.
    #[expect(dead_code)]
    pub(crate) fn await_msg<M: MessageFromGsp>(&self) -> Result<M>
    where
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        self.inner.lock().await_msg(None)
    }

    /// Logs and consumes every element the GSP has already posted, and returns without waiting for
    /// more.
    ///
    /// No caller is waiting for a reply while this holds the queue mutex, so every element is
    /// logged as an event. See "Draining the GSP-to-CPU queue" in
    /// `Documentation/gpu/nova/core/interrupts.rst`.
    ///
    /// # Errors
    ///
    /// `EIO` if the queue is poisoned, or if an element fails framing validation.
    pub(crate) fn drain(&self) -> Result {
        self.inner.lock().drain()
    }
}

/// Inner mutex protected state of [`Cmdq`].
struct CmdqInner<'a> {
    /// Device this command queue belongs to.
    dev: &'a device::Device,
    /// Next RPC sequence number, advanced once per logical command.
    rpc_seq: u32,
    /// Set once an element fails framing validation. Every later receive fails, since
    /// the bad element cannot be skipped. See "Draining the GSP-to-CPU queue" in
    /// `Documentation/gpu/nova/core/interrupts.rst`.
    ///
    /// A [`Cell`] because [`Self::wait_for_element`] sets it through `&self`.
    poisoned: Cell<bool>,
    /// Memory area shared with the GSP for communicating commands and messages.
    gsp_mem: DmaGspMem<'a>,
}

impl CmdqInner<'_> {
    /// Timeout for waiting for space on the command queue.
    const ALLOCATE_TIMEOUT: Delta = Delta::from_secs(1);

    /// Sends `command` to the GSP, without splitting it.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the command exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializers are propagated as-is.
    fn send_single_command<M>(&mut self, command: M, rpc_seq: u32) -> Result
    where
        M: CommandToGsp,
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        let size_in_bytes = command.size();
        let dst = self
            .gsp_mem
            .allocate_command(size_in_bytes, Self::ALLOCATE_TIMEOUT)?;

        // Extract area for the command itself. The GSP message header and the command header
        // together are guaranteed to fit entirely into a single page, so it's ok to only look
        // at `dst.contents.0` here.
        let (cmd, payload_1) = M::Command::from_bytes_mut_prefix(dst.contents.0).ok_or(EIO)?;

        // Fill the header and command in-place.
        let msg_element = GspMsgElement::init(rpc_seq, size_in_bytes, M::FUNCTION);
        // SAFETY: `msg_header` and `cmd` are valid references, and not touched if the initializer
        // fails.
        unsafe {
            pin_init::raw_try_init(core::ptr::from_mut(dst.header), msg_element)?;
            pin_init::raw_try_init(core::ptr::from_mut(cmd), command.init())?;
        }

        // Fill the variable-length payload, which may be empty.
        let mut sbuffer = SBufferIter::new_writer([&mut payload_1[..], &mut dst.contents.1[..]]);
        command.init_variable_payload(&mut sbuffer)?;

        if !sbuffer.is_empty() {
            return Err(EIO);
        }
        drop(sbuffer);

        dev_dbg!(
            &self.dev,
            "GSP RPC: send: seq# {}, function={:?}, length=0x{:x}\n",
            rpc_seq,
            M::FUNCTION,
            dst.header.length(),
        );

        // All set - update the write pointer and inform the GSP of the new command.
        let elem_count = dst.header.element_count();
        self.gsp_mem.advance_cpu_write_ptr(elem_count);

        Ok(())
    }

    /// Sends `command` to the GSP and returns the RPC sequence number assigned to it.
    ///
    /// The command may be split into multiple messages if it is large. The GSP echoes the
    /// sequence number in its reply.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if space does not become available within the timeout.
    /// - `EIO` if the variable payload requested by the command has not been entirely
    ///   written to by its [`CommandToGsp::init_variable_payload`] method.
    ///
    /// Error codes returned by the command initializers are propagated as-is.
    fn send_command<M>(&mut self, command: M) -> Result<u32>
    where
        M: CommandToGsp,
        Error: From<M::InitError>,
    {
        let rpc_seq = self.rpc_seq;
        self.rpc_seq = self.rpc_seq.wrapping_add(1);

        match SplitState::new(command)? {
            SplitState::Single(command) => self.send_single_command(command, rpc_seq)?,
            SplitState::Split(command, mut continuations) => {
                self.send_single_command(command, rpc_seq)?;

                while let Some(continuation) = continuations.next() {
                    // Turbofish needed because the compiler cannot infer M here.
                    self.send_single_command::<ContinuationRecord<'_>>(continuation, rpc_seq)?;
                }
            }
        }

        Ok(rpc_seq)
    }

    /// Logs `reason`, poisons the queue, and returns `EIO` for the caller to propagate.
    fn poison(&self, reason: fmt::Arguments<'_>) -> Error {
        dev_err!(&self.dev, "GSP receive: queue poisoned: {}\n", reason);
        self.poisoned.set(true);

        EIO
    }

    /// Sends a GMC API request to the GSP.
    ///
    /// `payload` follows the GMC header on the wire, and `max_response_size` is the largest
    /// response the caller accepts. The request takes the next RPC sequence number, which GSP-RM
    /// copies into its response. The number is spent even if the send fails.
    ///
    /// # Errors
    ///
    /// - `EMSGSIZE` if the request exceeds the maximum queue element size.
    /// - `ETIMEDOUT` if queue space does not become available within the timeout.
    /// - `EIO` if the element header is not properly aligned.
    fn send_gmc(&mut self, command_id: u32, payload: &[u8], max_response_size: u32) -> Result {
        let rpc_seq = self.rpc_seq;
        self.rpc_seq = self.rpc_seq.wrapping_add(1);

        let dst = self
            .gsp_mem
            .allocate_command::<GspGmcMsgElement>(payload.len(), Self::ALLOCATE_TIMEOUT)?;

        let msg_element = GspGmcMsgElement::init(
            command_id,
            u64::from(rpc_seq),
            payload.len(),
            max_response_size,
        );
        // SAFETY: `dst.header` points to a valid, writable `GspGmcMsgElement` region.
        unsafe {
            msg_element.__init(core::ptr::from_mut(dst.header))?;
        }

        SBufferIter::new_writer([&mut dst.contents.0[..], &mut dst.contents.1[..]])
            .write_all(payload)?;

        dev_dbg!(
            &self.dev,
            "GSP GMC: send: seq# {}, command_id=0x{:x}, length=0x{:x}\n",
            rpc_seq,
            command_id,
            dst.header.length(),
        );

        let elem_count = dst.header.element_count();
        self.gsp_mem.advance_cpu_write_ptr(elem_count);

        Ok(())
    }

    /// Waits for the next queue element and decodes it as the kind of message its NVDM type
    /// names.
    ///
    /// The element stays at the queue head. The caller advances the read pointer once it is done
    /// with the payload slices, which point into the queue.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if `timeout` has elapsed before any element becomes available.
    /// - `EIO` if the queue is already poisoned, or if the framing, the NVDM type or a declared
    ///   length is invalid, which poisons it (see [`Self::poisoned`]).
    fn wait_for_element(&self, timeout: Delta) -> Result<QueueElement<'_>> {
        if self.poisoned.get() {
            return Err(EIO);
        }

        let (slice_1, slice_2) = read_poll_timeout(
            || Ok(self.gsp_mem.driver_read_area()),
            |driver_area| !driver_area.0.is_empty(),
            Delta::from_millis(1),
            timeout,
        )
        .map(|(slice_1, slice_2)| (slice_1.as_flattened(), slice_2.as_flattened()))?;

        let Some((transport, _)) = QueueElementHeader::from_bytes_prefix(slice_1) else {
            return Err(self.poison(fmt!(
                "read area of {} bytes is shorter than a transport header",
                slice_1.len()
            )));
        };

        if transport.validate(size_of::<QueueElementHeader>()).is_err() {
            return Err(self.poison(fmt!(
                "element has bad MCTP framing, declared length {}",
                transport.element_len()
            )));
        }

        match transport.nvdm_type() {
            Ok(NvdmType::RmRpc) => {
                let Some((header, slice_1)) = GspMsgElement::from_bytes_prefix(slice_1) else {
                    return Err(
                        self.poison(fmt!("read area is shorter than an RPC element header"))
                    );
                };

                if header.validate_framing().is_err() {
                    return Err(self.poison(fmt!(
                        "RPC message with sequence {} declares length {}, less than its headers",
                        header.sequence(),
                        header.length()
                    )));
                }

                dev_dbg!(
                    &self.dev,
                    "GSP RPC: receive: seq# {}, function={:?}, length=0x{:x}\n",
                    header.sequence(),
                    header.function(),
                    header.length(),
                );

                let contents = self.payload_slices(slice_1, slice_2, header.payload_length())?;

                Ok(QueueElement::Rpc(GspMessage { header, contents }))
            }
            Ok(NvdmType::GmcApi) => {
                let Some((header, slice_1)) = GspGmcMsgElement::from_bytes_prefix(slice_1) else {
                    return Err(self.poison(fmt!("read area is shorter than a GMC element header")));
                };

                if header.validate_framing().is_err() {
                    return Err(self.poison(fmt!(
                        "GMC message with sequence {} declares length {}, less than its headers",
                        header.gmc.sequence,
                        header.length()
                    )));
                }

                dev_dbg!(
                    &self.dev,
                    "GSP GMC: receive: seq# {}, command_id=0x{:x}, length=0x{:x}\n",
                    header.gmc.sequence,
                    header.gmc.command_id(),
                    header.length(),
                );

                let contents = self.payload_slices(slice_1, slice_2, header.payload_length())?;

                Ok(QueueElement::Gmc(GmcMessage { header, contents }))
            }
            Ok(nvdm_type) => Err(self.poison(fmt!(
                "element carries NVDM type {:?}, which the GSP queues do not use",
                nvdm_type
            ))),
            Err(_) => Err(self.poison(fmt!("element carries an unknown NVDM type"))),
        }
    }

    /// Receives an element from the GSP and advances the read pointer past it. An RPC message
    /// whose function code is `M::FUNCTION` is decoded and returned. Any other RPC message is
    /// logged as an event, and a GMC message as unclaimed.
    ///
    /// With `expected_seq` set, the message must carry that RPC sequence number too. A message
    /// with the expected function code and a different sequence is a stale reply to a command
    /// that already timed out, so it is logged and dropped rather than classified as an event.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if `timeout` has elapsed before any element becomes available.
    /// - `EIO` if the queue is poisoned or the element fails framing validation (see
    ///   [`Self::wait_for_element`]), or if the matched message is too short for `M::Message`.
    /// - `ENOMSG` if the element was not the awaited reply.
    ///
    /// Error codes returned by [`MessageFromGsp::read`] are propagated as-is.
    fn receive_msg<M: MessageFromGsp>(
        &mut self,
        timeout: Delta,
        expected_seq: Option<u32>,
    ) -> Result<M>
    where
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        let element = self.wait_for_element(timeout)?;
        let element_count = element.element_count();

        // An early return here would leave the read pointer on this element.
        let result = match element {
            QueueElement::Gmc(message) => {
                self.log_gmc_event(message.header);

                Err(ENOMSG)
            }
            QueueElement::Rpc(message) => {
                let function = message.header.function();
                let seq = message.header.sequence();
                let func_matches = matches!(function, Ok(f) if f == M::FUNCTION);
                let matched = func_matches && expected_seq.is_none_or(|expected| seq == expected);

                if matched {
                    match M::Message::from_bytes_prefix(message.contents.0) {
                        Some((cmd, contents_1)) => {
                            let mut sbuffer =
                                SBufferIter::new_reader([contents_1, message.contents.1]);

                            M::read(cmd, &mut sbuffer)
                                .map_err(|e| e.into())
                                .inspect(|_| {
                                    if !sbuffer.is_empty() {
                                        dev_warn!(
                                            &self.dev,
                                            "GSP message {:?} has unprocessed data\n",
                                            M::FUNCTION
                                        );
                                    }
                                })
                        }
                        None => {
                            dev_warn!(&self.dev, "GSP message {:?} too short\n", M::FUNCTION);
                            Err(EIO)
                        }
                    }
                } else {
                    if func_matches {
                        dev_warn!(
                            &self.dev,
                            "GSP RPC: dropping stale {:?} reply (seq {}, awaiting {:?})\n",
                            M::FUNCTION,
                            seq,
                            expected_seq,
                        );
                    } else {
                        self.log_event(function, seq);
                    }

                    Err(ENOMSG)
                }
            }
        };

        self.gsp_mem.advance_cpu_read_ptr(element_count);

        result
    }

    /// Receives a message of type `M`, waiting up to [`Cmdq::RECEIVE_TIMEOUT`] from the call.
    ///
    /// Any other element that arrives first is logged and does not extend the deadline.
    /// `expected_seq` narrows the match as [`Self::receive_msg`] describes.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if no message of type `M` arrives before the deadline, however many other
    ///   elements arrive while waiting.
    /// - `EIO` if the queue is poisoned or an element fails framing validation (see
    ///   [`Self::wait_for_element`]).
    ///
    /// Error codes returned by [`MessageFromGsp::read`] are propagated as-is.
    fn await_msg<M: MessageFromGsp>(&mut self, expected_seq: Option<u32>) -> Result<M>
    where
        // This allows all error types, including `Infallible`, to be used for `M::InitError`.
        Error: From<M::InitError>,
    {
        let deadline = Instant::<Monotonic>::now() + Cmdq::RECEIVE_TIMEOUT;
        loop {
            let remaining = deadline - Instant::<Monotonic>::now();
            if remaining.is_negative() {
                break Err(ETIMEDOUT);
            }
            match self.receive_msg::<M>(remaining, expected_seq) {
                Ok(msg) => break Ok(msg),
                Err(ENOMSG) => continue,
                Err(e) => break Err(e),
            }
        }
    }

    /// Logs an event, meaning an RPC message that no caller was waiting for.
    ///
    /// An OS error or robust-channel record is logged at error level and an unknown function code
    /// at warning level. Every other event is recorded only by the receive trace in
    /// [`Self::wait_for_element`].
    fn log_event(&self, function: Result<MsgFunction, u32>, seq: u32) {
        match function {
            Ok(MsgFunction::OsErrorLog) => {
                dev_err!(&self.dev, "GSP reported an OS error (seq {})\n", seq);
            }
            Ok(MsgFunction::RcTriggered) => {
                dev_err!(
                    &self.dev,
                    "GSP triggered robust-channel recovery (seq {})\n",
                    seq
                );
            }
            // Nothing to do for the remaining known function codes.
            Ok(_) => {}
            Err(raw) => {
                dev_warn!(
                    &self.dev,
                    "unknown GSP message function {:#x} (seq {})\n",
                    raw,
                    seq
                );
            }
        }
    }

    /// Logs a GMC message that no caller was waiting for: a response to a request that already
    /// timed out, or an event that arrived outside the boot dispatch.
    fn log_gmc_event(&self, header: &GspGmcMsgElement) {
        dev_warn!(
            &self.dev,
            "GSP GMC: dropping unclaimed message (seq {}, command_id=0x{:x})\n",
            header.gmc.sequence,
            header.gmc.command_id(),
        );
    }

    /// Logs and consumes every element the queue holds.
    ///
    /// # Errors
    ///
    /// `EIO` if the queue is poisoned or an element fails framing validation.
    fn drain(&mut self) -> Result {
        while !self.gsp_mem.driver_read_area().0.is_empty() {
            // An element is available, so this returns without waiting.
            let element = self.wait_for_element(Delta::ZERO)?;
            let element_count = element.element_count();

            match element {
                QueueElement::Rpc(message) => {
                    self.log_event(message.header.function(), message.header.sequence());
                }
                QueueElement::Gmc(message) => self.log_gmc_event(message.header),
            }

            self.gsp_mem.advance_cpu_read_ptr(element_count);
        }

        Ok(())
    }

    /// Cuts the read area that follows a message header down to the `payload_length` bytes the
    /// header declares.
    ///
    /// # Errors
    ///
    /// - `EIO` if fewer bytes than that are readable, which poisons the queue.
    fn payload_slices<'a>(
        &self,
        slice_1: &'a [u8],
        slice_2: &'a [u8],
        payload_length: usize,
    ) -> Result<(&'a [u8], &'a [u8])> {
        if slice_1.len() + slice_2.len() < payload_length {
            return Err(self.poison(fmt!(
                "message advertises {} payload bytes but only {} are readable",
                payload_length,
                slice_1.len() + slice_2.len()
            )));
        }

        Ok(if slice_1.len() > payload_length {
            // PANIC: we checked above that `slice_1` is at least as long as `payload_length`.
            (slice_1.split_at(payload_length).0, &slice_2[0..0])
        } else {
            (
                slice_1,
                // PANIC: we checked above that `slice_1.len() + slice_2.len()` is at least as
                // large as `payload_length`.
                slice_2.split_at(payload_length - slice_1.len()).0,
            )
        })
    }

    /// Receives the next queue element. A GMC element goes to `handler` with its GMC header fields
    /// and the payload slices after that header, and `handler` returns `None` for an element it
    /// declines. The payload comes as two slices because the ring may wrap. An RPC element is
    /// logged as an event.
    ///
    /// Returns `Ok(None)` when nothing claimed the element. The read pointer advances past the
    /// element on every path.
    ///
    /// # Errors
    ///
    /// - `ETIMEDOUT` if no element arrives within `timeout`.
    /// - `EIO` if the queue is poisoned or the element fails framing validation, as
    ///   [`Self::wait_for_element`] describes.
    fn receive_gmc_and_dispatch<R>(
        &mut self,
        timeout: Delta,
        handler: impl FnOnce(u32, u32, &[u8], &[u8]) -> Option<R>,
    ) -> Result<Option<R>> {
        let element = self.wait_for_element(timeout)?;
        let element_count = element.element_count();

        let result = match element {
            QueueElement::Rpc(message) => {
                self.log_event(message.header.function(), message.header.sequence());

                None
            }
            QueueElement::Gmc(message) => {
                let header = message.header;

                if num::u32_as_usize(header.gmc.size) != header.payload_length() {
                    // GSP-RM writes both sizes from the same payload. If they differ, the driver
                    // cannot know which one is correct, so it drops the element.
                    dev_err!(
                        &self.dev,
                        "GSP GMC: payload is {} bytes, transport declares {}\n",
                        header.gmc.size,
                        header.payload_length(),
                    );

                    None
                } else {
                    handler(
                        header.gmc.command_id(),
                        header.gmc.max_resp_or_status,
                        message.contents.0,
                        message.contents.1,
                    )
                }
            }
        };

        self.gsp_mem.advance_cpu_read_ptr(element_count);

        Ok(result)
    }
}
